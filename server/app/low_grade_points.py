def assert_valid(points):
    keys = []
    for item in points:
        error = validate_card(item["kind"], item["prompt"], item["answer"])
        if error:
            raise ValueError(item["key"] + ": " + error)
        keys.append(item["key"])
    if len(keys) != len(set(keys)):
        raise ValueError("duplicate keys")
    return points
